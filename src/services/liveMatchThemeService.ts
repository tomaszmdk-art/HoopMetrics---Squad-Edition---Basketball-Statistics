export function getStoredLiveMatchTheme(): LiveMatchTheme {
  if (typeof window === 'undefined') return DEFAULT_LIVE_MATCH_THEME;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return DEFAULT_LIVE_MATCH_THEME;
    const parsed = JSON.parse(raw);
    return {
      ...DEFAULT_LIVE_MATCH_THEME,
      ...parsed,
      scoreboard: { ...defaultScoreboard, ...(parsed.scoreboard || {}) },
      playerCards: { ...defaultPlayerCards, ...(parsed.playerCards || {}) },
      actionTiles: { ...defaultActionTiles, ...(parsed.actionTiles || {}) },
    };
  } catch (err) {
    console.error('Błąd odczytu motywu LiveMatch:', err);
    return DEFAULT_LIVE_MATCH_THEME;
  }
}

export function saveLiveMatchTheme(theme: LiveMatchTheme): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(theme));
    window.dispatchEvent(new CustomEvent(THEME_CHANGE_EVENT, { detail: theme }));
  } catch (err) {
    console.error('Błąd zapisu motywu LiveMatch:', err);
  }
}

export function resetLiveMatchTheme(): LiveMatchTheme {
  saveLiveMatchTheme(DEFAULT_LIVE_MATCH_THEME);
  return DEFAULT_LIVE_MATCH_THEME;
}
